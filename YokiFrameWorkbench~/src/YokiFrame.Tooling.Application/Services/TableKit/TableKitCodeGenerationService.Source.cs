    /// <summary>按 Luban mapper 的真实 constructor 生成外部类型转换入口。</summary>
    /// <param name="helperNamespace">constructor 所属命名空间。</param>
    /// <param name="helperTypeName">constructor 所属静态类型名。</param>
    /// <param name="mappings">同一 helper 类型下的 bean mapper 列表。</param>
    /// <returns>C# 9 辅助源码。</returns>
    private static string BuildExternalTypeHelperSource(
        string helperNamespace,
        string helperTypeName,
        IReadOnlyList<TableKitExternalTypeMapping> mappings)
    {
        StringBuilder source = new();
        source.AppendLine("// <auto-generated>")
            .AppendLine("// Source: Luban bean mapper constructor.")
            .AppendLine("// 由 YokiFrame Workbench TableKit 直接生成，请勿手动修改。")
            .AppendLine("// </auto-generated>")
            .AppendLine()
            .AppendLine("namespace " + helperNamespace)
            .AppendLine("{")
            .AppendLine("    /// <summary>实现 Luban schema 中声明的外部类型 mapper。</summary>")
            .AppendLine("    public static class " + helperTypeName)
            .AppendLine("    {");
        foreach (TableKitExternalTypeMapping mapping in mappings)
        {
            AppendExternalTypeMapping(source, mapping);
        }
        source.AppendLine("    }")
            .AppendLine("}");
        return source.ToString();
    }

    /// <summary>写入一个 mapper 声明的目标类型、bean 参数和构造函数调用。</summary>
    /// <param name="source">目标源码构建器。</param>
    /// <param name="mapping">Luban XML 中解析出的 mapper。</param>
    private static void AppendExternalTypeMapping(StringBuilder source, TableKitExternalTypeMapping mapping)
    {
        source.AppendLine("        /// <summary>按 Luban mapper 把 bean 转换为目标类型。</summary>")
            .AppendLine("        /// <param name=\"value\">Luban 生成的 bean 值。</param>")
            .AppendLine("        /// <returns>mapper 声明的目标类型实例。</returns>")
            .Append("        public static ")
            .Append(mapping.TargetTypeName)
            .Append(' ')
            .Append(mapping.HelperMethodName)
            .Append("(")
            .Append(mapping.SourceTypeName)
            .AppendLine(" value)")
            .AppendLine("        {")
            .Append("            return new ")
            .Append(mapping.TargetTypeName)
            .Append("(")
            .Append(string.Join(", ", mapping.MemberNames.Select(static memberName => "value." + memberName)))
            .AppendLine(");")
            .AppendLine("        }")
            .AppendLine();
    }
