using System.Text;
using YokiFrame.Tooling.Application.Models.AudioKit;

namespace YokiFrame.Tooling.Application.Services.AudioKit;

/// <summary>承载 AudioKit C# 生成文本和标识符规范。</summary>
public sealed partial class AudioIndexService
{
    private static readonly HashSet<string> sCSharpKeywords = new(new[]
    {
        "class", "namespace", "public", "private", "internal", "static", "void", "int",
        "string", "new", "return", "null", "true", "false", "event", "base", "this"
    }, StringComparer.Ordinal);

    /// <summary>生成 C# 9 兼容常量类和只读路径映射。</summary>
    private static string BuildSource(
        IReadOnlyList<AudioIndexEntry> entries,
        string namespaceName,
        string className)
    {
        var builder = new StringBuilder(4096);
        builder.AppendLine("// <auto-generated>");
        builder.AppendLine("// Generated by YokiFrame AudioKit. Manual changes will be overwritten.");
        builder.AppendLine("// </auto-generated>");
        builder.AppendLine("using System.Collections.Generic;");
        builder.AppendLine();
        builder.Append("namespace ").Append(namespaceName).AppendLine();
        builder.AppendLine("{");
        AppendConstants(builder, entries, className);
        builder.AppendLine();
        AppendPaths(builder, entries, className);
        builder.AppendLine("}");
        return builder.ToString();
    }

    /// <summary>追加稳定整数常量类。</summary>
    private static void AppendConstants(
        StringBuilder builder,
        IReadOnlyList<AudioIndexEntry> entries,
        string className)
    {
        builder.AppendLine("    /// <summary>提供由 AudioKit manifest 分配的稳定音频 ID。</summary>");
        builder.Append("    public static class ").Append(className).AppendLine();
        builder.AppendLine("    {");
        for (var index = 0; index < entries.Count; index++)
        {
            AudioIndexEntry entry = entries[index];
            builder.Append("        /// <summary>").Append(EscapeXml(entry.Path)).AppendLine("</summary>");
            builder.Append("        public const int ").Append(entry.ConstantName)
                .Append(" = ").Append(entry.Id).AppendLine(";");
        }
        builder.AppendLine("    }");
    }

    /// <summary>追加 ID 到项目相对资源路径的只读映射。</summary>
    private static void AppendPaths(
        StringBuilder builder,
        IReadOnlyList<AudioIndexEntry> entries,
        string className)
    {
        builder.AppendLine("    /// <summary>提供稳定音频 ID 到项目相对路径的映射。</summary>");
        builder.AppendLine("    public static class AudioPaths");
        builder.AppendLine("    {");
        builder.AppendLine("        /// <summary>获取只读音频路径表。</summary>");
        builder.AppendLine("        public static readonly IReadOnlyDictionary<int, string> Map =");
        builder.AppendLine("            new Dictionary<int, string>");
        builder.AppendLine("            {");
        for (var index = 0; index < entries.Count; index++)
        {
            AudioIndexEntry entry = entries[index];
            builder.Append("                { ").Append(className).Append('.').Append(entry.ConstantName)
                .Append(", \"").Append(EscapeString(entry.Path)).AppendLine("\" },");
        }
        builder.AppendLine("            };");
        builder.AppendLine("    }");
    }

    /// <summary>从一级分类和文件名生成大写下划线常量名。</summary>
    private static string CreateConstantName(string name, string category)
    {
        var builder = new StringBuilder();
        AppendIdentifierPart(builder, category);
        if (builder.Length > 0) builder.Append('_');
        AppendIdentifierPart(builder, name);
        if (builder.Length == 0) builder.Append("AUDIO");
        if (char.IsDigit(builder[0])) builder.Insert(0, "AUDIO_");
        return builder.ToString();
    }

    /// <summary>追加大写字母数字并把其它字符折叠为单个下划线。</summary>
    private static void AppendIdentifierPart(StringBuilder builder, string value)
    {
        bool separator = builder.Length == 0 || builder[^1] == '_';
        for (var index = 0; index < value.Length; index++)
        {
            char current = value[index];
            if (char.IsLetterOrDigit(current))
            {
                if (char.IsUpper(current) && index > 0 && char.IsLower(value[index - 1]) && !separator) builder.Append('_');
                builder.Append(char.ToUpperInvariant(current));
                separator = false;
            }
            else if (!separator) { builder.Append('_'); separator = true; }
        }
        while (builder.Length > 0 && builder[^1] == '_') builder.Length--;
    }

    /// <summary>验证点分命名空间的每个 C# 标识符。</summary>
    private static void ValidateNamespace(string value)
    {
        string text = RequireText(value, "NamespaceName");
        string[] segments = text.Split('.');
        for (var index = 0; index < segments.Length; index++)
            ValidateIdentifier(segments[index], "NamespaceName");
    }

    /// <summary>验证 C# 标识符并拒绝保留关键字。</summary>
    private static void ValidateIdentifier(string value, string name)
    {
        string text = RequireText(value, name);
        if ((!char.IsLetter(text[0]) && text[0] != '_') || sCSharpKeywords.Contains(text))
            throw new InvalidDataException("AudioKit " + name + " is not a valid C# identifier: " + text);
        for (var index = 1; index < text.Length; index++)
        {
            if (!char.IsLetterOrDigit(text[index]) && text[index] != '_')
                throw new InvalidDataException("AudioKit " + name + " is not a valid C# identifier: " + text);
        }
    }

    /// <summary>转义 C# 字符串内容。</summary>
    private static string EscapeString(string value) => value.Replace("\\", "\\\\").Replace("\"", "\\\"");

    /// <summary>转义 XML 文档注释内容。</summary>
    private static string EscapeXml(string value) => value.Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;");
}
